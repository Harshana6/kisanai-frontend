import { useState } from 'react'
import { FaUpload, FaLeaf, FaSpinner, FaCheck, FaExclamationTriangle,FaDownload,FaCloudRain,FaBug,FaRobot,FaHistory } from 'react-icons/fa'
import { BiLoaderAlt } from "react-icons/bi";
import jsPDF from "jspdf";
import { useTranslation } from "react-i18next";
import { diagnoseLeaf } from "../services/leafService";
import i18n from "../i18n";
import AskAIModal from "../components/AskAIModal";
import { saveActivity } from "../utils/activityLogger";
import { toast } from "react-toastify";
function LeafDoctor() {
   const {t}=useTranslation();
  const [selectedFile, setSelectedFile] = useState(null)
  const [previewUrl, setPreviewUrl] = useState(null)
  const [analyzing, setAnalyzing] = useState(false)
  const [result, setResult] = useState(null)
  const [showAI, setShowAI] = useState(false);
  const handleFileSelect = (e) => {
    const file = e.target.files[0]
    if (file) {
      setSelectedFile(file)
      setPreviewUrl(URL.createObjectURL(file))
      setResult(null)
    }
  }

 const handleAnalyze = async () => {

  if (!selectedFile) return;

  try {

    setAnalyzing(true);

    const data = await diagnoseLeaf(selectedFile, i18n.language);

    console.log(data);

  if (data.success) {

    setResult(data);

    saveActivity({
        type: "leaf",
        title: data.disease,
        crop: data.disease,
        confidence: data.confidence,
        status:
            data.confidence >= 80
                ? "success"
                : data.confidence >= 60
                ? "warning"
                : "danger",
    });

}
else {
      const notify = ()=> toast.error("Analysis Failed");
      notify();
    }

  } catch (err) {

    console.log(err);
   const serverError = ()=> toast.error(err.response?.data?.message || "Server Error");
    
  } finally {

    setAnalyzing(false);

  }

};

  const resetAnalysis = () => {
    setSelectedFile(null)
    setPreviewUrl(null)
    setResult(null)
  }

  const getConfidenceColor = (confidence) => {
    if (confidence >= 80) return 'success'
    if (confidence >= 60) return 'warning'
    return 'danger'
  }

  // for generating report pdf
  const downloadReport = () => {
  if (!result) return;

  const doc = new jsPDF();

  // Header
  doc.setFillColor(45, 90, 39);
  doc.rect(0, 0, 210, 25, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.text("AI Plant Disease Analysis Report", 15, 16);

  // Reset text color
  doc.setTextColor(0);

  let y = 40;

  doc.setFontSize(16);
  doc.text("Plant Analysis", 15, y);

  y += 10;

  doc.setFontSize(12);

  doc.text(`Disease: ${result.disease}`, 15, y);
  y += 8;

  doc.text(`Confidence: ${result.confidence}%`, 15, y);
  y += 8;

  doc.text(`Severity: ${result.severity}`, 15, y);
  y += 8;

  doc.text(`Affected Area: ${result.affectedArea}`, 15, y);
  y += 8;

  doc.text(`Treatment Urgency: ${result.urgency}`, 15, y);

  y += 15;

  doc.setFontSize(15);
  doc.text("Description", 15, y);

  y += 8;

  doc.setFontSize(12);

  const description = doc.splitTextToSize(result.description, 180);

  doc.text(description, 15, y);

  y += description.length * 7 + 10;

  doc.setFontSize(15);
  doc.text("Treatment Recommendations", 15, y);

  y += 8;

  doc.setFontSize(12);

  result.recommendations.forEach((item, index) => {
    doc.text(`${index + 1}. ${item}`, 18, y);
    y += 8;
  });

  y += 12;

  doc.setDrawColor(45, 90, 39);
  doc.line(15, y, 195, y);

  y += 10;

  doc.setFontSize(10);
  doc.setTextColor(100);

  doc.text(
    `Generated on: ${new Date().toLocaleString()}`,
    15,
    y
  );

  doc.text(
    "Generated by Kisan AI",
    120,
    y
  );

  doc.save("Plant_Disease_Report.pdf");
};

  return (
    <>
    {/* Dynamic Keyframe Injection to guarantee rendering behavior */}
      <style>{`
        @keyframes customGlobalSpin {
          from { transform: rotate(0deg); }
          to { transform: rotate(360deg); }
        }
        .force-spin-icon {
          animation: customGlobalSpin 1.1s linear infinite !important;
          display: inline-block !important;
        }
      `}</style>
    <AskAIModal
    show={showAI}
    onClose={() => setShowAI(false)}
    diagnosis={result}
    language={localStorage.getItem("language") || "English"}
/>
    <div className="leaf-doctor fade-in">
      <div className="page-header">
        <h1 className="page-title">{t("leafDoctor.title")}</h1>
        <p className="page-subtitle">{t("leafDoctor.subtitle")}</p>
      </div>

      <div className="row g-4">
        <div className="col-12 col-lg-6">
          <div className="card">
            <div className="card-header">
              <h5 className="card-title mb-0">
                <FaLeaf className="me-2 text-success" />
                {t("leafDoctor.upload")}
              </h5>
            </div>
            <div className="card-body">
              {!previewUrl ? (
                <div className="upload-area" onClick={() => document.getElementById('fileInput').click()}>
                  <FaUpload className="upload-icon" />
                  <h6 className="mb-2"> {t("leafDoctor.dragDrop")}</h6>
                  <p className="mb-2">{t("leafDoctor.browse")}</p>
                  <small className="text-muted">Supports: JPG, PNG (Max 10MB)</small>
                </div>
              ) : (
                <div className="image-preview mb-3">
                  <img src={previewUrl} alt="Leaf preview" />
                </div>
              )}

              <input
                type="file"
                id="fileInput"
                accept="image/*"
                onChange={handleFileSelect}
                style={{ display: 'none' }}
              />

              {selectedFile && !result && (
                <div className="d-flex gap-2 mt-3">
                  <button
                    className="btn btn-primary flex-grow-1"
                    onClick={handleAnalyze}
                    disabled={analyzing}
                  >
                    {analyzing ? (
                      <>
  <BiLoaderAlt className="me-2 force-spin-icon" />
                        Analyzing...
                      </>
                    ) : (
                      <>
                        <FaLeaf className="me-2" />
                        {t("leafDoctor.analyze")}
                      </>
                    )}
                  </button>
                  <button className="btn btn-outline-secondary" onClick={resetAnalysis}>
                    {t("leafDoctor.clear")}
                  </button>
                </div>
              )}

              {result && (
                <button className="btn btn-outline-primary w-100 mt-3" onClick={resetAnalysis}>
                  {t("leafDoctor.uploadNew")}
                </button>
              )}
            </div>
          </div>

          <div className="card mt-4">
            <div className="card-header">
              <h5 className="card-title mb-0">How to Capture Best Results</h5>
            </div>
            <div className="card-body">
              <ul className="feature-list">
                <li>
                  <FaCheck className="check-icon" />
                  <span>Use natural lighting for clear images</span>
                </li>
                <li>
                  <FaCheck className="check-icon" />
                  <span>Capture both healthy and affected areas</span>
                </li>
                <li>
                  <FaCheck className="check-icon" />
                  <span>Keep camera 10-15cm from leaf surface</span>
                </li>
                <li>
                  <FaCheck className="check-icon" />
                  <span>Ensure leaf is in focus and well-lit</span>
                </li>
                <li>
                  <FaCheck className="check-icon" />
                  <span>Avoid shadows and reflections</span>
                </li>
              </ul>
            </div>
          </div>
        </div>

        <div className="col-12 col-lg-6">
          {
            analyzing ? (
              <div className="card h-100">
    <div className="card-body d-flex flex-column justify-content-center align-items-center">

     <BiLoaderAlt className="text-success mb-3 force-spin-icon" size={55} />

      <h4>AI is analyzing your crop...</h4>

      <p className="text-muted">
        Detecting disease...
      </p>

      <div className="progress w-100 mt-3">
        <div
          className="progress-bar progress-bar-striped progress-bar-animated"
          style={{ width: "100%" }}
        ></div>
      </div>

    </div>
  </div>
            ):
          result ? (
            <div>
              <div className="card">
                <div className="card-header bg-light">
                  <h5 className="card-title mb-0">
                    <FaCheck className="me-2 text-success" />
                   {t("leafDoctor.analysis")}
                  </h5>
                </div>
                <div className="card-body">
                  <div className="row g-3 mb-4">
                    <div className="col-6">
                      <div className="p-3 bg-light rounded-3 text-center">
                        <div className="result-icon"><FaLeaf></FaLeaf></div>
                        <h4 className="mb-1 text-primary">{result.disease}</h4>
                        <small className="text-muted">{t("leafDoctor.disease")}</small>
                      </div>
                    </div>
                    <div className="col-6">
                      <div className="p-3 bg-light rounded-3 text-center">
                        <div className="result-icon">🎯</div>
                        <h4 className={`mb-1 text-${getConfidenceColor(result.confidence)}`}>
                          {result.confidence}%
                        </h4>
                        <small className="text-muted">{t("leafDoctor.confidence")}</small>
                      </div>
                    </div>
                  </div>

                  <div className="row g-3 mb-4">
                    <div className="col-xl-4 col-lg-4 col-md-4 col-sm-12 col-12">
                      <div className="text-center">
                        <div  className="result-icon">⚠</div>
                        <span className="badge bg-warning fs-6">{result.severity}</span>
                        <p className="small text-muted mt-2 mb-0">{t("leafDoctor.severity")}</p>
                      </div>
                    </div>
                    <div className="col-xl-4 col-lg-4 col-md-4 col-sm-12 col-12">
                      <div className="text-center">
                        <div className="result-icon">🍃</div>
                        <span className="badge bg-info fs-6">{result.affectedArea}</span>
                        <p className="small text-muted mt-2 mb-0">{t("leafDoctor.affected")}</p>
                      </div>
                    </div>
                    <div className="col-xl-4 col-lg-4 col-md-4 col-sm-12 col-12">
                      <div className="text-center">
                        <div className="result-icon">⏰</div>
                        <span className="badge bg-danger fs-6">{result.urgency}</span>
                        <p className="small text-muted mt-2 mb-0">{t("leafDoctor.urgency")}</p>
                      </div>
                    </div>
                  </div>

                  <div className="alert alert-success mb-0">
                    <strong>{t("leafDoctor.description:")}</strong>
                    <p className="mb-0 mt-2">{result.description}</p>
                  </div>
                </div>
              </div>

              <div className="card mt-4">
                <div className="card-header bg-success text-white">
                  <h5 className="card-title mb-0">{t("leafDoctor.recommendations")}</h5>
                </div>
                <div className="card-body">
                  <ul className="list-group">

{result.recommendations.map((rec,index)=>(

<li key={index} className="list-group-item">

<input
type="checkbox"
className="form-check-input me-2"
/>

{rec}

</li>

))}

</ul>
                </div>
              </div>
              <div className="card mt-4">

{/* <div className="card-header bg-primary text-white">

<FaRobot></FaRobot>  {t("leafDoctor.ai")}

</div> */}

{/* <div className="card-body">

<p>

Because humidity is high today,

spray Copper Fungicide tomorrow morning

between 7 AM and 9 AM.

Avoid watering for 24 hours.

Expected recovery:

7-10 Days.

</p>

</div> */}

</div>
            </div>
          ) : (
            <div className="card h-100">
              <div className="card-body d-flex flex-column align-items-center justify-content-center text-center py-5">
                <FaExclamationTriangle className="text-muted mb-3" size={48} />
                <h5 className="text-muted mb-2">{t("leafDoctor.noAnalysis")}</h5>
                <p className="text-muted small mb-0">
                  Upload a leaf image and click "Analyze Disease" to get AI-powered diagnostics and treatment recommendations.
                </p>
              </div>
            </div>
          )}
        </div>
          {
            result?(
               <div className="row mt-4 g-3">

<div className="col-md-4">

<button disabled={i18n.language !== "en"} className="btn btn-success w-100"
onClick={downloadReport}>

<FaDownload></FaDownload> {t("leafDoctor.download")}

</button>

</div>


<div className="col-md-4">

<button className="btn btn-warning w-100"

   onClick={() => {
    console.log("Button Clicked");
    setShowAI(true);
  }}>

<FaRobot></FaRobot> {t("common.askAI")}

</button>

</div>

<div className="col-md-4">

<button
className="btn btn-outline-success w-100"
onClick={resetAnalysis}
>

🔄 {t("leafDoctor.analyzeAgain")}

</button>

</div>

</div>
            ):(
              <div></div>
            )

          }
      </div>
    </div></>
  )
}

export default LeafDoctor
